export type AKey = keyof typeof pt;
const DICTS: Record<Lang, Dict> = { pt, en, es };
let lang: Lang = 'pt';

export const setALang = (l: Lang) => (lang = l);
export const aLang = () => lang;

export function at(key: AKey, vars: Record<string, string | number> = {}): string {
  return DICTS[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}

/** Preposição + nome da UF ("no Rio de Janeiro", "in Bahia", "en São Paulo"). */
const NO = new Set(['AC', 'AM', 'AP', 'CE', 'DF', 'ES', 'MA', 'PA', 'PI', 'PR', 'RJ', 'RN', 'RS', 'TO']);
const NA = new Set(['BA', 'PB']);
export function inUf(uf: string, nome: string): string {
  if (lang === 'en') return `in ${nome}`;
  if (lang === 'es') return `en ${nome}`;
  return `${NO.has(uf) ? 'no' : NA.has(uf) ? 'na' : 'em'} ${nome}`;
}

export function applyAStatic() {
  document.querySelectorAll<HTMLElement>('[data-a]').forEach((el) => (el.textContent = at(el.dataset.a as AKey)));
  document.querySelectorAll<HTMLElement>('[data-a-html]').forEach((el) => (el.innerHTML = at(el.dataset.aHtml as AKey)));
  document.querySelectorAll<HTMLElement>('[data-a-aria]').forEach((el) => el.setAttribute('aria-label', at(el.dataset.aAria as AKey)));
  document.querySelectorAll<HTMLInputElement>('[data-a-ph]').forEach((el) => (el.placeholder = at(el.dataset.aPh as AKey)));
  document.title = at('title');
}
